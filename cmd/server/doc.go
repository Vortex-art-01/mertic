// Сервер сбора метрик: принимает метрики от агентов, хранит их и отдаёт по HTTP.
//
// Хранилище выбирается при старте. Если задана строка подключения к PostgreSQL,
// метрики пишутся в базу, а схему при подключении создают миграции. Иначе
// метрики хранятся в памяти и сохраняются в файл: по таймеру или после каждого
// изменения.
//
// # Запуск
//
//	server [-a адрес] [-d dsn] [-f файл] [-i секунды] [-r=false] [-k ключ]
//	       [--audit-file файл] [--audit-url url] [--pprof-addr адрес]
//
// Любой флаг можно задать и переменной окружения, причём переменная важнее флага:
//
//	-a            ADDRESS            адрес HTTP-сервера; по умолчанию localhost:8080
//	-d            DATABASE_DSN       строка подключения к PostgreSQL
//	-f            FILE_STORAGE_PATH  файл дампа; по умолчанию /tmp/metrics-db.json,
//	                                 пустое значение выключает дамп
//	-i            STORE_INTERVAL     период записи дампа в секундах; по умолчанию 300,
//	                                 0 — писать после каждого изменения
//	-r            RESTORE            загружать метрики из дампа при старте; по умолчанию true
//	-k            KEY                ключ подписи HMAC-SHA256; пустой выключает подпись
//	--audit-file  AUDIT_FILE         файл для событий аудита
//	--audit-url   AUDIT_URL          URL для событий аудита
//	--pprof-addr  PPROF_ADDRESS      адрес профилировщика net/http/pprof
//
// # HTTP API
//
//	GET  /                              HTML-страница со всеми метриками
//	GET  /ping                          200, если база доступна; без базы — всегда 200
//	GET  /value/{type}/{name}           значение метрики текстом
//	POST /value/                        метрика с текущим значением; тело — model.Metrics
//	POST /update/{type}/{name}/{value}  обновить метрику через URL
//	POST /update/                       обновить метрику; тело — model.Metrics
//	POST /updates/                      обновить пакет метрик; тело — []model.Metrics
//
// JSON-эндпоинты отвечают и на пути без завершающей косой черты. Каждый
// эндпоинт обслуживает свой пакет в internal/handler: там описаны тела и коды
// ответов, а в example_test.go лежат примеры запросов. Запросы проходят через
// мидлвари из internal/middleware: лог, gzip, предел размера тела и проверку
// подписи. Тело запроса после распаковки не может быть больше мегабайта: на
// больший запрос сервер отвечает 413.
//
// По SIGINT и SIGTERM сервер перестаёт принимать соединения, дорабатывает
// начатые запросы, записывает последний дамп и разбирает очереди аудита.
