// Staticlint — статический анализатор кода проекта.
//
// Это multichecker: одна программа, в которой собраны стандартные анализаторы
// из golang.org/x/tools, проверки staticcheck, три сторонних анализатора и
// собственный анализатор osexit. Проверяемую программу он не запускает:
// читает исходный код, проверяет типы и сообщает о местах, где код ошибается,
// делает лишнюю работу или написан не так, как принято в Go.
//
// # Запуск
//
// Анализатор собирают и запускают из корня репозитория. Аргументы — шаблоны
// пакетов, те же, что у go build и go vet:
//
//	go build -o cmd/staticlint/staticlint ./cmd/staticlint
//	./cmd/staticlint/staticlint ./...
//
// То же одной командой, без файла на диске:
//
//	go run ./cmd/staticlint ./...
//
// Замечания печатаются в stderr, по одному на строку:
//
//	cmd/app/main.go:12:3: direct call to os.Exit in function main of package main
//
// Код возврата 0 значит, что замечаний нет, 3 — что они есть, 1 — что пакеты
// не загрузились или какой-то анализатор завершился ошибкой.
//
// Второй способ — передать собранный анализатор команде go vet:
//
//	go vet -vettool=cmd/staticlint/staticlint ./...
//
// Замечания те же, но код возврата при них — 1: его выставляет go vet. В
// Windows имя файла в этих командах пишется с расширением: staticlint.exe.
//
// # Флаги
//
// Без флагов работают все анализаторы. Флаги ставятся перед шаблонами пакетов
// и действуют при обоих способах запуска:
//
//	-ИМЯ          запустить только названные анализаторы: -osexit -shadow
//	-ИМЯ=false    запустить все анализаторы, кроме названных
//	-ИМЯ.флаг     флаг самого анализатора: -shadow.strict
//	-fix          применить исправления, которые предлагают анализаторы
//	-diff         вместе с -fix: показать исправления, не меняя файлы
//	-json         вывести замечания в stdout в формате JSON; код возврата — 0
//	-c N          показать вместе с замечанием N строк кода вокруг него
//	-test=false   не проверять тесты; только при автономном запуске: go vet
//	              решает сам, какие пакеты проверять
//
// Список анализаторов с краткими описаниями печатает команда help, а полное
// описание анализатора и его флаги — help с его именем:
//
//	staticlint help
//	staticlint help osexit
//
// # Как устроен запуск
//
// Функция main собирает анализаторы в один список и передаёт его в
// multichecker.Main из golang.org/x/tools/go/analysis/multichecker. Дальше
// работает она:
//
//  1. Проверяет сам набор: у каждого анализатора есть имя, описание и функция
//     запуска, а зависимости между анализаторами не образуют цикл.
//  2. Заводит флаги — общие и по флагу -ИМЯ на каждый анализатор — и
//     разбирает командную строку.
//  3. Через go list находит пакеты по шаблонам и загружает их вместе с
//     тестами и всеми зависимостями, включая стандартную библиотеку:
//     разбирает исходный код и проверяет типы.
//  4. Строит граф действий «анализатор — пакет» и выполняет его параллельно.
//     Действие ждёт анализаторы, на результаты которых опирается его
//     анализатор, — общий обход синтаксического дерева, SSA-представление
//     функций — и факты о пакетах, которые импортирует его пакет.
//  5. Печатает замечания к пакетам, названным в командной строке, и завершает
//     процесс с кодом возврата.
//
// Факты — то, что анализатор узнал об одном пакете и что пригодится ему в
// другом. Например, printf запоминает, что функция — обёртка над fmt.Printf,
// и проверяет строки формата в её вызовах из других пакетов. Ради фактов
// зависимости разбираются из исходного кода целиком, поэтому автономный
// запуск держит в памяти сразу весь код программы: на этом проекте это
// несколько гигабайт. Анализатору, собранному под 32-битную платформу
// (GOARCH=386), на это не хватает адресного пространства.
//
// Запуск через go vet устроен иначе. Пакеты в порядке зависимостей обходит
// сама команда go и на каждый запускает анализатор отдельным процессом,
// передавая ему файл настроек с расширением .cfg; multichecker.Main узнаёт
// такой запуск по этому аргументу. Факты процессы передают друг другу через
// файлы, а go сохраняет их в кэше сборки. Каждому процессу нужен только один
// пакет, поэтому памяти хватает и 32-битной сборке, а повторный запуск заново
// проверяет только то, что изменилось.
//
// # Стандартные анализаторы
//
// Из golang.org/x/tools/go/analysis/passes взяты почти все анализаторы; какие
// не взяты и почему, сказано в конце раздела. Большая часть взятых — набор
// go vet в том виде, в каком он описан в golang.org/x/tools/go/analysis/suite/vet;
// сверх него добавлены atomicalign, deepequalerrors, gofixdirective, httpmux,
// inline, nilness, reflectvaluecompare, shadow, sortslice и unusedwrite.
//
//	appends              append без добавляемых значений: append(s)
//	asmdecl              ассемблерная функция расходится с объявлением на Go
//	assign               переменная присваивается самой себе: x = x
//	atomic               x = atomic.AddInt64(&x, 1): из-за присваивания
//	                     операция перестаёт быть атомарной
//	atomicalign          64-битное значение для sync/atomic не выровнено по
//	                     8 байт: на 32-битной платформе это паника
//	bools                ошибки в логических выражениях: повтор условия
//	                     a == 1 || a == 1, всегда истинное x != 1 || x != 2
//	buildtag             неверные директивы //go:build и // +build
//	cgocall              нарушены правила передачи указателей в cgo
//	composites           литерал структуры из другого пакета без имён полей
//	copylocks            мьютекс или структура с ним копируется по значению
//	deepequalerrors      ошибки сравниваются через reflect.DeepEqual
//	defers               time.Since в аргументе defer вычисляется сразу, а не
//	                     при выходе из функции
//	directive            директива тулчейна вроде //go:debug стоит не на месте
//	errorsas             второй аргумент errors.As — не указатель на интерфейс
//	                     или на тип, реализующий error
//	framepointer         ассемблер портит указатель кадра, не сохранив его
//	gofixdirective       директивой //go:fix inline помечено то, что
//	                     подставить нельзя
//	hostport             адрес для net.Dial собран через fmt.Sprintf("%s:%d"):
//	                     с IPv6 это не работает, нужен net.JoinHostPort
//	httpmux              шаблон http.ServeMux с методом или подстановкой в
//	                     модуле с Go старше 1.22
//	httpresponse         defer resp.Body.Close() стоит до проверки ошибки
//	                     запроса
//	ifaceassert          приведение интерфейса к интерфейсу, которое не может
//	                     удаться
//	inline               вызов функции или константа, помеченные директивой
//	                     //go:fix inline: их пора заменить тем, на что они
//	                     ссылаются
//	loopclosure          замыкание захватывает переменную цикла: до Go 1.22
//	                     она была общей на все итерации
//	lostcancel           функция отмены контекста вызывается не на всех путях
//	nilfunc              функция сравнивается с nil: результат известен заранее
//	nilness              разыменование заведомо нулевого указателя и сравнения
//	                     с nil, исход которых известен заранее
//	printf               аргументы Printf-подобной функции не подходят к
//	                     строке формата
//	reflectvaluecompare  reflect.Value сравниваются через == или
//	                     reflect.DeepEqual
//	scannererr           после цикла по bufio.Scanner.Scan не проверен
//	                     Scanner.Err
//	shadow               переменная во вложенном блоке заслоняет одноимённую
//	                     внешнюю, которая используется после него
//	shift                сдвиг на число бит, не меньшее разрядности числа
//	sigchanyzer          в signal.Notify передан небуферизованный канал:
//	                     сигнал может потеряться
//	slog                 в вызове log/slog ключ не строка или ключу не хватает
//	                     значения
//	sortslice            в sort.Slice передан не срез
//	sqlrowserr           после цикла по sql.Rows.Next не проверен Rows.Err
//	stdmethods           у метода с именем из стандартного интерфейса —
//	                     WriteTo, MarshalJSON — другая сигнатура
//	stdversion           используется символ стандартной библиотеки новее
//	                     версии Go из go.mod
//	stringintconv        string(int) даёт символ с таким кодом, а не запись
//	                     числа
//	structtag            тег поля структуры записан не по правилам
//	                     reflect.StructTag
//	testinggoroutine     t.Fatal и подобные вызваны из горутины, которую
//	                     запустил тест
//	tests                ошибки в именах и сигнатурах тестов, бенчмарков и
//	                     примеров
//	timeformat           формат времени 2006-02-01, год-день-месяц, вместо
//	                     2006-01-02
//	unmarshal            в Unmarshal или Decode передан не указатель
//	unreachable          код, до которого выполнение не дойдёт
//	unsafeptr            uintptr преобразуется в unsafe.Pointer с нарушением
//	                     правил
//	unusedresult         отброшен результат функции, вызванной только ради
//	                     него: fmt.Sprintf, errors.New, slices.Clone
//	unusedwrite          запись в поле копии структуры или в элемент копии
//	                     массива, которую никто не прочтёт
//	waitgroup            WaitGroup.Add вызван внутри горутины, а не перед ней
//
// Из пакета modernize взят набор modernize.Suite: на нём построена команда
// go fix. Его анализаторы находят код, для которого в языке или стандартной
// библиотеке появилась более короткая запись, и предлагают исправление — его
// применяет флаг -fix. Замена, которой нужна версия Go новее указанной в
// go.mod, не предлагается.
//
//	any                interface{} → any
//	atomictypes        atomic.AddInt32(&x, 1) над обычной переменной →
//	                   переменная типа atomic.Int32
//	embedlit           литерал встроенной структуры T{U: U{x: 1}} → T{x: 1},
//	                   с Go 1.27
//	errorsastype       var e *T и errors.As(err, &e) → errors.AsType[*T](err)
//	forvar             копия переменной цикла x := x, лишняя с Go 1.22
//	importcomment      устаревший комментарий // import "путь" у имени пакета
//	mapsloop           цикл, копирующий словарь → maps.Copy, maps.Clone
//	minmax             if/else, выбирающий меньшее или большее → min, max
//	newexpr            функция вида func(x T) *T { return &x } → new(x)
//	omitzero           omitempty у поля-структуры, где он не действует →
//	                   omitzero
//	plusbuild          устаревшая строка // +build рядом с //go:build
//	rangeint           for i := 0; i < n; i++ → for i := range n
//	reflecttypeassert  v.Interface().(T) → reflect.TypeAssert[T](v)
//	reflecttypefor     reflect.TypeOf(T{}) → reflect.TypeFor[T]()
//	slicesbackward     цикл по срезу с конца → slices.Backward
//	slicesclip         s[:len(s):len(s)] → slices.Clip(s)
//	slicescontains     цикл, ищущий элемент → slices.Contains
//	slicessort         sort.Slice с простым сравнением → slices.Sort
//	stditerators       цикл по Len и At → итератор того же типа
//	stringsbuilder     строка, которую собирают через += → strings.Builder
//	stringscut         strings.Index и срез строки → strings.Cut
//	stringscutprefix   HasPrefix и TrimPrefix → strings.CutPrefix
//	stringsseq         range по strings.Split → strings.SplitSeq, без среза
//	testingcontext     context.WithCancel в тесте → t.Context()
//	unsafefuncs        арифметика указателей через uintptr → unsafe.Add
//	waitgroupgo        wg.Add(1) и go с defer wg.Done() → wg.Go
//
// Не включены:
//
//   - fieldalignment: указывает не на ошибку, а на возможность сэкономить
//     несколько байт, переставив поля структуры. На этом проекте он даёт 32
//     замечания, и ни одно не уменьшило бы размер структуры: все — о числе
//     байт, которые просматривает сборщик мусора. Читать структуру после
//     такой перестановки труднее, а в go vet анализатор не включён как
//     слишком шумный;
//   - appendclipped, bloop, fmtappendf и slicesdelete из пакета modernize:
//     авторы пакета не включили их в modernize.Suite, потому что их замены
//     меняют поведение кода или делают его менее понятным;
//   - buildssa, ctrlflow, inspect и usesgenerics: о замечаниях не сообщают, а
//     готовят данные для других анализаторов, которые подключают их сами;
//   - findcall и pkgfact: учебные примеры к самому механизму анализа.
//
// # Проверки staticcheck
//
// Из honnef.co/go/tools взяты классы SA, S и ST целиком и четыре проверки
// класса QF. У каждой проверки есть страница с примерами:
// https://staticcheck.dev/docs/checks.
//
// SA1 — стандартная библиотека используется неправильно:
//
//	SA1000  некорректное регулярное выражение
//	SA1001  некорректный шаблон text/template или html/template
//	SA1002  некорректный формат времени в time.Parse
//	SA1003  функции encoding/binary передан тип без фиксированного размера:
//	        int, строка, словарь
//	SA1004  подозрительно малое число без единицы времени в time.Sleep
//	SA1005  в exec.Command команда с аргументами передана одной строкой
//	SA1006  Printf с непостоянной строкой формата и без аргументов
//	SA1007  некорректный URL в url.Parse
//	SA1008  ключ в словаре http.Header записан не в каноническом виде
//	SA1010  (*regexp.Regexp).FindAll с n == 0 всегда возвращает пустой
//	        результат
//	SA1011  функции пакета strings передана строка с некорректным UTF-8
//	SA1012  вместо контекста передан nil: нужен context.TODO
//	SA1013  в io.Seeker.Seek перепутаны аргументы: whence стоит первым
//	SA1014  в Unmarshal или Decode передан не указатель
//	SA1015  time.Tick там, где тикер нельзя остановить: до Go 1.23 это
//	        утечка, нужен time.NewTicker
//	SA1016  перехват сигнала, который перехватить нельзя: SIGKILL, SIGSTOP
//	SA1017  в signal.Notify передан небуферизованный канал
//	SA1018  strings.Replace с n == 0 ничего не заменяет
//	SA1019  используется то, что помечено как Deprecated
//	SA1020  некорректный адрес host:port в net.Listen и подобных
//	SA1021  net.IP сравниваются через bytes.Equal вместо net.IP.Equal
//	SA1023  реализация io.Writer изменяет переданный ей срез
//	SA1024  в наборе символов для strings.TrimLeft и подобных символы
//	        повторяются: вероятно, нужен TrimPrefix
//	SA1025  используется результат (*time.Timer).Reset, на который нельзя
//	        полагаться
//	SA1026  в JSON или XML сериализуется канал или функция
//	SA1027  атомарная операция над 64-битной переменной без выравнивания
//	        по 8 байт
//	SA1028  в sort.Slice передан не срез
//	SA1029  ключ context.WithValue — строка или другой встроенный тип вместо
//	        собственного
//	SA1030  некорректный аргумент функции пакета strconv
//	SA1031  кодировщику Encode(dst, src) переданы перекрывающиеся срезы
//	SA1032  в errors.Is перепутаны аргументы
//
// SA2 — ошибки в конкурентном коде:
//
//	SA2000  WaitGroup.Add вызван внутри горутины: гонка с Wait
//	SA2001  пустая критическая секция: Unlock сразу за Lock, вероятно,
//	        пропущен defer
//	SA2002  t.FailNow или t.SkipNow вызваны из горутины
//	SA2003  defer Lock сразу после Lock: вероятно, нужен defer Unlock
//
// SA3 — ошибки в тестах:
//
//	SA3000  TestMain не вызывает os.Exit, и провал тестов не виден; важно до
//	        Go 1.15
//	SA3001  присваивание b.N в бенчмарке искажает результат
//
// SA4 — код, который ничего не делает:
//
//	SA4000  по обе стороны оператора стоят одинаковые выражения
//	SA4001  &*x равно x и копии не создаёт
//	SA4003  беззнаковое число сравнивается с отрицательным
//	SA4004  цикл безусловно завершается на первой итерации
//	SA4005  присваивание полю в методе с получателем-значением: его никто
//	        не увидит
//	SA4006  значение переменной перезаписано, так и не будучи прочитанным
//	SA4008  переменная в условии цикла не меняется: вероятно, увеличивается
//	        не та
//	SA4009  аргумент функции перезаписан до первого использования
//	SA4010  результат append нигде не используется
//	SA4011  break ничего не прерывает: вероятно, нужен выход из внешнего
//	        цикла
//	SA4012  сравнение с NaN: оно всегда ложно
//	SA4013  двойное отрицание !!b
//	SA4014  в цепочке if/else if повторяется условие
//	SA4015  math.Ceil и подобные вызваны для числа, полученного из целого
//	SA4016  битовая операция без эффекта, например x ^ 0
//	SA4017  отброшен результат функции без побочных эффектов
//	SA4018  переменная присваивается самой себе
//	SA4019  одинаковые ограничения сборки в одном файле
//	SA4020  недостижимая ветка в переключателе типов
//	SA4021  x = append(y) без добавляемых значений — то же, что x = y
//	SA4022  адрес переменной сравнивается с nil
//	SA4023  с nil сравнивается интерфейс, который nil быть не может
//	SA4024  результат встроенной функции проверяется на невозможное
//	        значение: len(x) < 0
//	SA4025  целочисленное деление литералов даёт ноль: 2 / 3
//	SA4026  константа -0.0: отрицательный ноль так не получить
//	SA4027  изменяется копия, которую вернул (*url.URL).Query: сам URL
//	        остаётся прежним
//	SA4028  x % 1 всегда равно нулю
//	SA4029  sort.StringSlice(x) и подобные — преобразование типа, а не
//	        сортировка
//	SA4030  rand.Intn(1) и подобные всегда возвращают ноль
//	SA4031  с nil сравнивается значение, которое nil быть не может
//	SA4032  runtime.GOOS или runtime.GOARCH сравнивается со значением,
//	        невозможным при ограничениях сборки файла
//
// SA5 — ошибки, которые проявятся при выполнении:
//
//	SA5000  запись в nil-словарь
//	SA5001  defer Close стоит до проверки ошибки открытия
//	SA5002  пустой цикл for {} занимает процессор и может блокировать
//	        планировщик
//	SA5003  defer в бесконечном цикле никогда не выполнится
//	SA5004  for { select { ... } } с пустой веткой default крутится вхолостую
//	SA5005  финализатор ссылается на свой объект и не даёт его собрать
//	SA5007  бесконечная рекурсия
