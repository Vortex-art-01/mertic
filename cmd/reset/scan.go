const (
	// mark — комментарий, которым помечают структуры.
	mark = "generate:reset"

	// fileName — файл пакета, в который записываются его методы Reset.
	fileName = "reset.gen.go"

	// header открывает каждый созданный файл. По нему утилита отличает свои
	// файлы от чужих, а go vet, staticcheck и редакторы узнают сгенерированный
	// код: строка соответствует соглашению из go help generate.
	header = "// Code generated by cmd/reset; DO NOT EDIT."

	// tagKey — ключ тега поля: с тегом reset:"-" генератор поле не трогает.
	tagKey = "reset"
)

// generator — состояние одного запуска: какие типы получат метод Reset, какие
// старые файлы будут переписаны или удалены и какие ошибки найдены.
type generator struct {
	dir  string // корневой каталог: от него считаются пути в сообщениях
	fset *token.FileSet

	// marked — помеченные структуры всех загруженных пакетов, по ключу typeKey.
	// Метод Reset у них появится в этом запуске, даже если его ещё нет.
	marked map[string]bool

	// stale — файлы reset.gen.go, которые утилита создала раньше. Их методы не в
	// счёт: файл будет переписан или удалён.
	stale map[string]bool

	problems []problem
}

func newGenerator(dir string, fset *token.FileSet) *generator {
	return &generator{
		dir:    dir,
		fset:   fset,
		marked: make(map[string]bool),
		stale:  make(map[string]bool),
	}
}

// unit — загруженный пакет и то, что в нём нашлось.
type unit struct {
	pkg      *packages.Package
	name     string         // имя пакета в его исходниках
	path     string         // файл reset.gen.go этого пакета
	existing []byte         // его текущее содержимое; nil — файла нет
	ours     bool           // текущий файл создан утилитой
	targets  []*types.Named // помеченные структуры в порядке объявления
}

// problem — ошибка, из-за которой утилита не меняет файлы.
type problem struct {
	file      string // путь относительно корневого каталога; пусто — места нет
	line, col int
	msg       string
}

func (p problem) String() string {
	switch {
	case p.file == "":
		return p.msg
	case p.line == 0:
		return p.file + ": " + p.msg
	case p.col == 0:
		return fmt.Sprintf("%s:%d: %s", p.file, p.line, p.msg)
	default:
		return fmt.Sprintf("%s:%d:%d: %s", p.file, p.line, p.col, p.msg)
	}
}

func (g *generator) problemf(pos token.Pos, format string, args ...any) {
	p := g.fset.Position(pos)

	g.problems = append(g.problems, problem{
		file: displayPath(g.dir, p.Filename),
		line: p.Line,
		col:  p.Column,
		msg:  fmt.Sprintf(format, args...),
	})
}

// sortedProblems возвращает ошибки по порядку их мест в исходниках.
func (g *generator) sortedProblems() []problem {
	slices.SortFunc(g.problems, func(a, b problem) int {
		return cmp.Or(
			cmp.Compare(a.file, b.file),
			cmp.Compare(a.line, b.line),
			cmp.Compare(a.col, b.col),
			cmp.Compare(a.msg, b.msg),
		)
	})

	return slices.Compact(g.problems)
}

// scan находит в пакете помеченные структуры и проверяет разметку. Пакет,
// который обработать нельзя, scan пропускает и возвращает nil, см. loadFailed.
func (g *generator) scan(pkg *packages.Package) *unit {
	if g.loadFailed(pkg) {
		return nil
	}

	dir := pkg.Dir
	if dir == "" {
		dir = filepath.Dir(pkg.GoFiles[0])
	}

	u := &unit{pkg: pkg, path: filepath.Join(dir, fileName)}

	data, err := os.ReadFile(u.path)
	switch {
	case err == nil:
		u.existing = data
		u.ours = generatedByUs(data)
		if u.ours {
			g.stale[u.path] = true
		}
	case !errors.Is(err, fs.ErrNotExist):
		g.problems = append(g.problems, problem{msg: err.Error()})
		return nil
	}

	var specs []*ast.TypeSpec
	for _, file := range pkg.Syntax {
		if g.isOwnFile(u, file) {
			continue
		}

		// Имя пакета берётся из исходников, а не у go list: если пакет
		// переименовали, старый reset.gen.go ещё носит прежнее имя.
		if u.name == "" {
			u.name = file.Name.Name
		}

		specs = append(specs, g.markedSpecs(file)...)
	}

	resets := g.handwrittenResets(u)
	for _, spec := range specs {
		g.addTarget(u, spec, resets)
	}

	return u
}

// loadFailed сообщает, что пакет обработать нельзя, и записывает причину.
//
// Пакет без исходников, кроме тестов, утилита пропускает молча. Но если go list
// при этом сообщил об ошибке, это шаблон, под который не попал ни один каталог,
// или каталог без файлов для текущей платформы, и молча пропустить его значило
// бы скрыть опечатку в аргументах.
//
// В пакете с исходниками помехой считается только файл, который не разобрался:
// без полного синтаксического дерева нельзя ни найти все метки, ни заменить
// файл пакета. Остальные ошибки не мешают, см. loadPackages. Среди них и ошибки
// go list: export data он получает, компилируя пакеты, и код, который ещё до
// генерации вызывает Reset у помеченной структуры, приходит ошибкой go list, а
// не ошибкой типов. Если же из-за ошибки не определился тип поля, о поле
// сообщит checkFields.
func (g *generator) loadFailed(pkg *packages.Package) bool {
	if len(pkg.GoFiles) == 0 {
		for _, err := range pkg.Errors {
			g.problems = append(g.problems, g.loadProblem(err))
		}

		return true
	}

	failed := false

	for _, err := range pkg.Errors {
		if err.Kind == packages.ParseError {
			g.problems = append(g.problems, g.loadProblem(err))
			failed = true
		}
	}

	return failed
}

// loadProblem превращает ошибку go/packages в problem с путём относительно
// корневого каталога, как у ошибок разметки.
func (g *generator) loadProblem(err packages.Error) problem {
	file, line, col, ok := splitPos(err.Pos)
	if !ok {
		if err.Pos == "" || err.Pos == "-" {
			return problem{msg: err.Msg}
		}

		return problem{msg: err.Pos + ": " + err.Msg}
	}

	return problem{file: displayPath(g.dir, file), line: line, col: col, msg: err.Msg}
}

// splitPos разбирает позицию из ошибки go/packages: файл:строка:столбец или
// файл:строка. Имя файла в Windows само содержит двоеточие после буквы диска,
// поэтому числа отделяются с конца.
func splitPos(pos string) (file string, line, col int, ok bool) {
	i := strings.LastIndexByte(pos, ':')
	if i < 0 {
		return "", 0, 0, false
	}

	last, err := strconv.Atoi(pos[i+1:])
	if err != nil {
		return "", 0, 0, false
	}

	file = pos[:i]

	j := strings.LastIndexByte(file, ':')
	if j < 0 {
		return file, last, 0, true
	}

	first, err := strconv.Atoi(file[j+1:])
	if err != nil {
		// Перед этим двоеточием — буква диска: число в позиции одно, это строка.
		return file, last, 0, true
	}

	return file[:j], first, last, true
}

// generatedByUs сообщает, создан ли файл с содержимым data этой утилитой. Чужой
// файл с тем же именем она не перезапишет и не удалит.
func generatedByUs(data []byte) bool {
	line, _, _ := bytes.Cut(data, []byte("\n"))

	return string(bytes.TrimSuffix(line, []byte("\r"))) == header
}

// isOwnFile сообщает, что file — reset.gen.go пакета, созданный утилитой.
func (g *generator) isOwnFile(u *unit, file *ast.File) bool {
	return u.ours && g.isStale(file.Package)
}

// isStale сообщает, что pos лежит в старом файле утилиты, который этот запуск
// перепишет или удалит.
func (g *generator) isStale(pos token.Pos) bool {
	return g.stale[filepath.Clean(g.fset.Position(pos).Filename)]
}

// markedSpecs возвращает объявления типов с меткой. Метка над сгруппированным
// объявлением type (...) относится ко всем типам группы. Метку над функцией,
// переменной, константой или импортом markedSpecs считает ошибкой: так метка
// не потеряется молча.
func (g *generator) markedSpecs(file *ast.File) []*ast.TypeSpec {
	var specs []*ast.TypeSpec

	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if hasMark(d.Doc) {
				g.problemf(d.Pos(), "%s applies only to struct types, not to functions", mark)
			}

		case *ast.GenDecl:
			if d.Tok != token.TYPE {
				g.misplacedMarks(d)
				continue
			}

			for _, spec := range d.Specs {
				if ts := spec.(*ast.TypeSpec); hasMark(d.Doc) || hasMark(ts.Doc) {
					specs = append(specs, ts)
				}
			}
		}
	}

	return specs
}

// misplacedMarks сообщает о метках над объявлением import, const или var и над
// отдельными его элементами.
func (g *generator) misplacedMarks(d *ast.GenDecl) {
	if hasMark(d.Doc) {
		g.problemf(d.Pos(), "%s applies only to struct types, not to %s declarations", mark, d.Tok)
	}

	for _, spec := range d.Specs {
		var doc *ast.CommentGroup

		switch s := spec.(type) {
		case *ast.ValueSpec:
			doc = s.Doc
		case *ast.ImportSpec:
			doc = s.Doc
		}

		if hasMark(doc) {
			g.problemf(spec.Pos(), "%s applies only to struct types, not to %s declarations", mark, d.Tok)
		}
	}
}

// hasMark сообщает, есть ли среди строк комментария doc метка. Подходят оба
// вида: // generate:reset и //generate:reset. Второй go doc считает директивой
// и в документации не показывает.
func hasMark(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}

	return slices.ContainsFunc(doc.List, func(c *ast.Comment) bool {
		text, ok := strings.CutPrefix(c.Text, "//")
		return ok && strings.TrimSpace(text) == mark
	})
}

// handwrittenResets находит методы Reset, объявленные в пакете вручную, и
// группирует их по имени типа получателя. Старый файл утилиты не в счёт: он
// будет переписан.
func (g *generator) handwrittenResets(u *unit) map[string][]token.Pos {
	resets := make(map[string][]token.Pos)

	for _, file := range u.pkg.Syntax {
		if g.isOwnFile(u, file) {
			continue
		}

		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || len(fn.Recv.List) == 0 || fn.Name.Name != "Reset" {
				continue
			}

			if name := receiverTypeName(fn.Recv.List[0].Type); name != "" {
				resets[name] = append(resets[name], fn.Pos())
			}
		}
	}

	return resets
}

// receiverTypeName возвращает имя типа получателя: T для T, *T, T[K, V] и
// (*T).
func receiverTypeName(expr ast.Expr) string {
	for {
		switch e := expr.(type) {
		case *ast.Ident:
			return e.Name
		case *ast.StarExpr:
			expr = e.X
		case *ast.ParenExpr:
			expr = e.X
		case *ast.IndexExpr:
			expr = e.X
		case *ast.IndexListExpr:
			expr = e.X
		default:
			return ""
		}
	}
}

// addTarget проверяет помеченное объявление spec и добавляет структуру в
// список пакета. resets — методы Reset, написанные в пакете вручную.
func (g *generator) addTarget(u *unit, spec *ast.TypeSpec, resets map[string][]token.Pos) {
	name := spec.Name.Name

	if spec.Assign.IsValid() {
		g.problemf(spec.Pos(), "%s is an alias: mark the type it refers to instead", name)
		return
	}

	obj, ok := u.pkg.TypesInfo.Defs[spec.Name].(*types.TypeName)
	if !ok {
		g.problemf(spec.Pos(), "cannot resolve type %s", name)
		return
	}

	named, ok := obj.Type().(*types.Named)
	if !ok {
		g.problemf(spec.Pos(), "cannot resolve type %s", name)
		return
	}

	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		g.problemf(spec.Pos(), "%s is not a struct type: %s applies only to structs", name, mark)
		return
	}

	for _, pos := range resets[name] {
		g.problemf(pos, "%s is marked %s but already has method Reset", name, mark)
	}

	for f := range st.Fields() {
		if f.Name() == "Reset" {
			g.problemf(f.Pos(), "field Reset of %s conflicts with the generated method Reset", name)
		}
	}

	g.checkFields(st)

	g.marked[typeKey(obj)] = true
	u.targets = append(u.targets, named)
}

// typeKey — ключ типа в generator.marked: путь пакета и имя типа.
func typeKey(obj *types.TypeName) string {
	return obj.Pkg().Path() + "." + obj.Name()
}

// checkFields проверяет поля структуры st, которые генератору предстоит
// сбросить: тег reset допустим, тип поля известен. Поля анонимных структур
// генератор сбрасывает по отдельности, поэтому проверяет и их.
func (g *generator) checkFields(st *types.Struct) {
	for i := range st.NumFields() {
		f := st.Field(i)

		tag, tagged := reflect.StructTag(st.Tag(i)).Lookup(tagKey)
		if tagged && tag != "-" {
			g.problemf(f.Pos(), "field %s: unsupported tag value %s:%q, only %s:\"-\" is allowed", f.Name(), tagKey, tag, tagKey)
			continue
		}

		if tagged || f.Name() == "_" {
			continue
		}

		if hasInvalid(f.Type()) {
			g.problemf(f.Pos(), "field %s: cannot determine its type", f.Name())
			continue
		}

		if inner := innerStruct(f.Type()); inner != nil {
			g.checkFields(inner)
		}
	}
}

// innerStruct возвращает анонимную структуру, до которой генератор дойдёт от
// значения типа t через указатели и массивы, или nil, если такой нет.
func innerStruct(t types.Type) *types.Struct {
	for {
		switch u := types.Unalias(t).(type) {
		case *types.Pointer:
			t = u.Elem()
		case *types.Array:
			t = u.Elem()
		case *types.Struct:
			return u
		default:
			return nil
		}
	}
}

// hasInvalid сообщает, есть ли в типе t часть, которую не удалось определить:
// например, неизвестный тип или тип из пакета, который не загрузился.
// Устройство именованных типов hasInvalid не разбирает, а сигнатуры функций
// пропускает: поле-функцию генератор только обнуляет.
func hasInvalid(t types.Type) bool {
	switch t := types.Unalias(t).(type) {
	case *types.Basic:
		return t.Kind() == types.Invalid
	case *types.Named:
		if b, ok := t.Underlying().(*types.Basic); ok && b.Kind() == types.Invalid {
			return true
		}

		for arg := range t.TypeArgs().Types() {
			if hasInvalid(arg) {
				return true
			}
		}
	case *types.Pointer:
		return hasInvalid(t.Elem())
	case *types.Slice:
		return hasInvalid(t.Elem())
	case *types.Array:
		return hasInvalid(t.Elem())
	case *types.Chan:
		return hasInvalid(t.Elem())
	case *types.Map:
		return hasInvalid(t.Key()) || hasInvalid(t.Elem())
	case *types.Struct:
		for f := range t.Fields() {
			if hasInvalid(f.Type()) {
				return true
			}
		}
	}

	return false
}

// change решает, что делать с файлом reset.gen.go пакета: записать новое
// содержимое, удалить файл или оставить как есть.
func (g *generator) change(u *unit) (change, bool) {
	if len(u.targets) == 0 {
		// Помеченных структур в пакете не осталось: свой старый файл утилита
		// удаляет, а чужой файл с тем же именем ей не принадлежит.
		if u.existing != nil && u.ours {
			return change{path: u.path}, true
		}

		return change{}, false
	}

	if u.existing != nil && !u.ours {
		g.problems = append(g.problems, problem{
			file: displayPath(g.dir, u.path),
			line: 1,
			col:  1,
			msg:  fmt.Sprintf("file was not generated by cmd/reset, refusing to overwrite it: rename the file or remove the %s comments in the package", mark),
		})

		return change{}, false
	}

	data, ok := g.render(u)
	if !ok || (u.existing != nil && sameContent(u.existing, data)) {
		return change{}, false
	}

	return change{path: u.path, data: data}, true
}
