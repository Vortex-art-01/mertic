// Reset создаёт методы Reset() для структур, помеченных комментарием
// generate:reset.
//
// Reset возвращает объект к начальному состоянию, но оставляет ему память,
// которую можно занять снова: слайсы обрезаются до нулевой длины с прежней
// ёмкостью, мапы очищаются, значения по указателям сбрасываются на месте. Так
// объект можно переиспользовать, например через sync.Pool, и не выделять
// память заново.
//
// # Запуск
//
// Утилиту запускают из корня репозитория:
//
//	go run ./cmd/reset
//
// Она просматривает все пакеты от текущего каталога вниз, находит помеченные
// структуры и для каждого пакета, где они есть, записывает их методы в файл
// reset.gen.go рядом с исходниками пакета. Вместо всех пакетов можно назвать
// нужные — шаблонами, как у go build:
//
//	go run ./cmd/reset ./internal/...
//
// Утилита печатает, какие файлы записала или удалила. Файл, содержимое
// которого не изменилось, она не трогает, так что повторный запуск ничего не
// меняет. Ошибки разметки печатаются по одной на строку:
//
//	internal/pool/pool.go:12:6: IDs is not a struct type: generate:reset applies only to structs
//
// Если нашлась хоть одна ошибка, утилита не меняет ни одного файла и
// завершается с кодом 1.
//
// # Разметка
//
// Метка ставится над объявлением структуры, как doc-комментарий, — без пустой
// строки между ними:
//
//	// generate:reset
//	type ResetableStruct struct {
//		i     int
//		str   string
//		strP  *string
//		s     []int
//		m     map[string]string
//		child *ResetableStruct
//	}
//
// Для неё утилита создаст метод:
//
//	// Reset сбрасывает ResetableStruct для повторного использования.
//	func (rs *ResetableStruct) Reset() {
//		if rs == nil {
//			return
//		}
//
//		rs.i = 0
//		rs.str = ""
//		if rs.strP != nil {
//			*rs.strP = ""
//		}
//		rs.s = rs.s[:0]
//		clear(rs.m)
//		if rs.child != nil {
//			rs.child.Reset()
//		}
//	}
//
// Метка может быть и одной из строк doc-комментария. Подходит и запись
// //generate:reset, без пробела: go doc считает её директивой и в документации
// не показывает. Метка над сгруппированным объявлением type (...) относится ко
// всем типам группы. Над функцией, переменной, константой, импортом,
// псевдонимом и типом, который не структура, метка — ошибка. У помеченной
// структуры не должно быть своего метода Reset и поля с таким именем.
//
// Обобщённые структуры тоже подходят: метод объявляется у *T[P1, P2]. Получатель
// называется так же, как в других методах типа, а если их нет — первыми
// буквами слов имени типа. Метод можно вызвать и у nil: он ничего не сделает.
//
// # Правила сброса
//
// Как сбросить поле, утилита решает по его типу:
//
//	число, строка, bool        нулевое значение: 0, "", false
//	слайс                      s = s[:0]: длина 0, ёмкость прежняя
//	мапа                       clear(m): мапа та же, но пустая
//	тип с методом Reset()      вызов Reset(); у интерфейса — если он не nil
//	указатель                  если не nil, значение по нему сбрасывается по
//	                           этим же правилам, а сам указатель не меняется
//	структура без Reset()      нулевое значение T{}
//	анонимная структура        каждое поле по этим же правилам
//	массив                     каждый элемент по этим же правилам; если все
//	                           элементы обнуляются, массив обнуляется целиком
//	интерфейс, канал, функция  nil
//	параметр типа              нулевое значение *new(T)
//
// Метод Reset() — без параметров и результатов — ищется по правилам Go для
// вызова x.Reset(): у самого типа или у встроенных в него полей. Поэтому
// bytes.Buffer и strings.Builder сбрасываются своим методом, а bufio.Reader,
// у которого метод Reset(io.Reader), обнуляется, как любая структура без
// Reset(). Помеченная структура считается типом с Reset() ещё до того, как
// метод создан, в том числе в другом пакете. Не в счёт метод, до которого Go
// добирается через встроенный указатель или интерфейс: у нулевого значения
// struct{ *bytes.Buffer } вызов Reset() упал бы с паникой.
//
// Структура без Reset() по указателю не меняется: указатель мог прийти извне,
// и обнулить, например, общий *slog.Logger значило бы сломать его для всех.
// Чтобы такое поле сбрасывалось, пометьте его тип или храните структуру по
// значению.
//
// Поле можно исключить из сброса тегом reset:"-". Это нужно для зависимостей,
// которые объект получает один раз при создании, и для указателей, по которым
// сброс пошёл бы по кругу: у дерева с указателем на родителя Reset ребёнка
// сбросил бы и родителя, а у двусвязного списка вызывал бы сам себя, пока не
// кончится стек.
//
//	// generate:reset
//	type node struct {
//		value    []byte
//		children []*node
//		parent   *node `reset:"-"`
//	}
//
// Пустые поля _ утилита пропускает: обратиться к ним по имени нельзя. Мьютексы
// и другие структуры из sync обнуляются как обычные поля, поэтому вызывать
// Reset, держа блокировку объекта, нельзя. Как и обычное присваивание полям,
// Reset не защищён от одновременного доступа из других горутин.
//
// # Файл reset.gen.go
//
// Методы всех помеченных структур пакета утилита записывает в один файл
// reset.gen.go, в порядке объявления структур. Файл начинается строкой
//
//	// Code generated by cmd/reset; DO NOT EDIT.
//
// По ней go vet, staticcheck и редакторы узнают сгенерированный код, а сама
// утилита — свои файлы. Свой файл она переписывает, а когда в пакете не
// остаётся помеченных структур, удаляет. Чужой файл с тем же именем она не
// трогает, а если в его пакете есть метки, сообщает об ошибке.
//
// Код форматируется так же, как gofmt. Пакеты, на которые он ссылается,
// утилита импортирует сама, под именем, не занятым в пакете. Окончания строк
// при сравнении со старым файлом не учитываются: в Windows git с настройкой
// core.autocrlf=true выдаёт файлы с CRLF, и актуальный файл из-за этого не
// переписывается.
//
// # Ограничения
//
//   - Тесты не просматриваются: метод из reset.gen.go не может ссылаться на тип
//     из файла _test.go.
//   - Ограничения сборки вычисляются для текущих GOOS и GOARCH, без тегов:
//     структура из файла, который на этой платформе не собирается, не
//     найдётся. Теги можно передать через GOFLAGS=-tags=....
//   - Просматриваются только объявления уровня пакета: у типа, объявленного
//     внутри функции, методов быть не может.
//   - Шаблон ./... пропускает каталоги testdata и те, чьё имя начинается с
//     точки или подчёркивания, — как go build.
//
// # Как устроена
//
// Пакеты загружает golang.org/x/tools/go/packages. Он запускает go list,
// разбирает исходники найденных пакетов и проверяет их типы, а типы
// зависимостей читает из export data, которую go list получает компиляцией.
// Исходники зависимостей в память не загружаются, поэтому утилите хватает
// памяти и на всём проекте, даже в 32-битной сборке.
//
// Ошибки типов утилите не мешают: код, который вызывает Reset у помеченной
// структуры, не скомпилируется, пока метода нет, а создать его как раз и
// нужно. По той же причине не мешают и ошибки go list в пакете с исходниками:
// export data go list получает компиляцией, и о таком коде сообщает и он.
// Ошибкой считаются файл, который не разобрался, поле, тип которого определить
// не удалось, и шаблон, под который не попал ни один пакет.
//
// Метки утилита ищет в синтаксических деревьях (go/ast), а как сбросить поле,
// решает по его типу (go/types). Есть ли у типа метод Reset(), она проверяет
// сама, повторяя правила поиска методов Go: проверка типов видит код таким, как
// он есть, а утилите нужен код после запуска — с методами помеченных структур
// и без методов из старых файлов reset.gen.go.
//
// Тело метода пишется дважды. Первый проход узнаёт, на какие имена ссылается
// тело: пакеты, типы, nil и clear. Второй пишет его с именами получателя и
// переменных циклов, которые ни одно из этих имён не перекрывают.
