// Агент собирает метрики рантайма Go и системы и отправляет их на сервер.
//
// Каждые POLL_INTERVAL секунд агент снимает 27 метрик runtime.MemStats,
// случайное число RandomValue, объём памяти и загрузку каждого ядра CPU, а раз
// в REPORT_INTERVAL секунд отправляет накопленное одним пакетом на
// POST /updates/ вместе со счётчиком опросов PollCount. Пакет сжимается gzip и,
// если задан ключ, подписывается HMAC-SHA256.
//
// # Запуск
//
//	agent [-a адрес] [-p секунды] [-r секунды] [-k ключ] [-l число]
//
// Любой флаг можно задать и переменной окружения, причём переменная важнее флага:
//
//	-a  ADDRESS          адрес сервера; по умолчанию localhost:8080
//	-p  POLL_INTERVAL    период опроса метрик в секундах, не меньше 1; по умолчанию 2
//	-r  REPORT_INTERVAL  период отправки в секундах, не меньше 1; по умолчанию 10
//	-k  KEY              ключ подписи HMAC-SHA256; пустой выключает подпись
//	-l  RATE_LIMIT       сколько запросов к серверу можно держать одновременно,
//	                     не меньше 1; по умолчанию 1
//
// По SIGINT и SIGTERM агент прекращает опрос, прерывает незавершённые отправки и
// завершается.
