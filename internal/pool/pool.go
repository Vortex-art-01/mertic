// Package pool переиспользует объекты, которые умеют сбрасывать своё состояние
// методом Reset.
//
// [Pool] — типизированная обёртка над [sync.Pool]. Сам sync.Pool хранит any,
// поэтому каждый Get требует утверждения типа, а сбросить объект перед возвратом
// должен не забыть каждый, кто его возвращает. Забытый сброс ничего не ломает
// сразу: объект просто достаётся следующему владельцу с данными прошлого. Pool
// берёт и то и другое на себя: [Pool.Get] возвращает значение нужного типа, а
// [Pool.Put] сам вызывает Reset. Тип без этого метода в пул не положить: такой
// код не скомпилируется.
//
// Методы Reset для структур проекта создаёт утилита cmd/reset, а у многих типов
// стандартной библиотеки, например у [bytes.Buffer], такой метод уже есть.
package pool

import "sync"

// Resetter — объект, который умеет вернуться к начальному состоянию. Reset
// стирает всё, что осталось от прошлого использования, но может сохранить
// выделенную память: ради неё объект и переиспользуют.
type Resetter interface {
	Reset()
}

// Pool хранит свободные объекты типа T. Им можно пользоваться из нескольких
// горутин одновременно.
//
// Объекты хранит sync.Pool, поэтому и ведёт себя Pool так же: число объектов не
// ограничено, а свободные забирает сборщик мусора — пул отдаёт ему те, что
// пролежали без дела две сборки подряд. Get может вернуть как прежний объект,
// так и только что созданный.
//
// T должен быть указателем или другим ссылочным типом, например мапой. Значение
// иного типа при каждом Put копируется в кучу — это та самая аллокация, от
// которой пул должен избавлять. У sync.Pool такую ошибку ловит проверка SA6002
// из cmd/staticlint, но сквозь параметр типа она её не видит.
//
// Пул создаёт [New]: нулевое значение Pool непригодно. Копировать Pool после
// первого использования нельзя.
type Pool[T Resetter] struct {
	pool sync.Pool
}

// New возвращает пустой пул. Когда свободных объектов нет, Get создаёт новый
// функцией newFn; возвращать nil она не должна. Если nil сама newFn, New
// паникует: так ошибка проявится при создании пула, а не на первом Get под
// нагрузкой.
func New[T Resetter](newFn func() T) *Pool[T] {
	if newFn == nil {
		panic("pool: New called with nil newFn")
	}

	p := &Pool[T]{}
	p.pool.New = func() any { return newFn() }

	return p
}

// Get возвращает свободный объект, а если свободных нет — новый, созданный
// функцией из [New]. Свободный объект уже сброшен: это делает Put.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает x методом Reset и возвращает в пул. Сброс при возврате, а не
// при выдаче, нужен затем, чтобы свободный объект не удерживал данные прошлого
// владельца, пока лежит в пуле: ни память под них, ни объекты по ссылкам.
//
// После Put нельзя пользоваться ни x, ни тем, что он отдал наружу, например
// срезами своего буфера: объект достанется следующему Get, возможно, в другой
// горутине. x не должен быть nil — следующий Get вернул бы его. Объект, который
// хранить незачем, например разросшийся буфер, в пул просто не возвращают: его
// заберёт сборщик мусора.
func (p *Pool[T]) Put(x T) {
	x.Reset()
	p.pool.Put(x)
}
