// Package gzippool переиспользует компрессоры gzip: каждый держит таблицы примерно
// на 800 КБ, и создавать его заново на каждый поток слишком дорого.
//
// sync.Pool здесь не подходит: у него своё хранилище на каждый P, а объект из
// приватного слота другому P недоступен. Компрессор нужен редко, поэтому такой пул
// то и дело промахивается и при этом накапливает порядка GOMAXPROCS компрессоров.
// Общий список свободных компрессоров удерживает строго ограниченный объём памяти, а
// всем, кому компрессора не хватило, создаётся временный.
package gzippool

import (
	"compress/gzip"
	"io"
)

// maxIdle — сколько свободных компрессоров хранить. Больших ответов мало, и одновременно
// их сжимают редко: под нагрузкой второй запасной компрессор сокращал выделения памяти
// на 8%, но удерживал ещё 800 КБ.
const maxIdle = 1

var idle = make(chan *gzip.Writer, maxIdle)

// Get возвращает компрессор, пишущий в w.
func Get(w io.Writer) *gzip.Writer {
	select {
	case zw := <-idle:
		zw.Reset(w)
		return zw
	default:
		return gzip.NewWriter(w)
	}
}

// Put забирает компрессор обратно. Reset отвязывает его от прошлого получателя:
// свободный компрессор может лежать сколько угодно долго и не должен удерживать
// соединение или буфер. Если свободных уже достаточно, этот достанется сборщику мусора.
func Put(zw *gzip.Writer) {
	zw.Reset(io.Discard)

	select {
	case idle <- zw:
	default:
	}
}
